/** Desenha um glifo 16x16 escalado para `size`, na cor dada. */
export function glyph(name, size, color, opts = {}) {
  const paths = GLYPHS[name];
  if (!paths) return "";
  const { x = 0, y = 0, strokeOnly = false } = opts;
  const s = size / 16;
  const fill = strokeOnly ? "none" : color;
  return `<g transform="translate(${x}, ${y}) scale(${s.toFixed(4)})">
    ${paths.map((d) => `<path d="${d}" fill="${fill}" />`).join("")}
  </g>`;
}
